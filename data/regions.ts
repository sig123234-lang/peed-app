export const SIDO_LIST = Object.keys(BY_SIDO);

export const REGIONS: Region[] = SIDO_LIST.flatMap((sido) =>
  BY_SIDO[sido].map((name) => ({ sido, name }))
);

/** 저장·비교에 쓰는 고유 키. 예: "서울 마포구", "경기 고양시 덕양구" */
export function regionKey(r: Region): string {
  return `${r.sido} ${r.name}`;
}

export function findRegion(key: string): Region | null {
  return REGIONS.find((r) => regionKey(r) === key) ?? null;
}

/**
 * 주소 문자열에서 지역을 찾는다.
 *
 * 이름이 긴 것부터 본다 — "고양시 덕양구" 와 "중구" 가 둘 다 걸릴 수 있는데
 * 더 구체적인 쪽이 맞다. 시도명이 주소에 있으면 그것도 함께 맞아야 한다.
 * "중구" 처럼 여러 시도에 같은 이름이 있기 때문이다.
 */
export function matchRegion(address: string): Region | null {
  const text = String(address || '');
  if (!text) return null;

  const hit = [...REGIONS]
    .sort((a, b) => b.name.length - a.name.length)
    .filter((r) => r.name.split(' ').every((tok) => text.includes(tok)));
  if (!hit.length) return null;

  // 시도까지 맞는 후보를 우선한다(동명 구 구분).
  const withSido = hit.find((r) => text.includes(r.sido));
  return withSido ?? hit[0];
}
